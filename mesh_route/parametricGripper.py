    BRAID_TOTAL_MASS       = 1e-1      # kg, ~0.1 g per node (unphysically high but solver-friendly)

    # Central inextensible TENDON (finger3): a free cable down the hollow
    # centre, endpoints tethered into the base/tip plates, edges made stiff
    # so the base->tip distance is capped (~inextensible). Wired only when a
