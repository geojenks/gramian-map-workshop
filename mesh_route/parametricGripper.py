    # Bladder/braid contact (two-body McKibben only). Constraint-based
    # (FrictionContactConstraint, mu=0 — frictionless: braid strands
    # slide freely on the bladder). The contact distance acts as the
    # effective strand radius: skin and braid centreline are kept this
    # far apart once contact engages, so the radial deadband travelled
    # before engagement is braid_clearance - CONTACT_DISTANCE.
    # Constraint contact is REQUIRED by the scene architecture: the ODE
    # solver lives inside Finger1, so penalty-contact force fields
    # (which CollisionResponse attaches at root) are never visited by
    # the mechanical visitors and silently do nothing — verified
    # empirically (braid sailed through the bladder with penalty
    # response while the same detection pairs restrained it as
    # constraints). Constraints are collected globally by the root
    # GenericConstraintSolver, which is placement-independent.
    # Cost containment for the O(10^2) contact rows: solver
    # multithreading + the coarser default meshes from make_mckibben.
    # CONTACT_ALARM_DISTANCE must stay BELOW the rest braid_clearance:
    # every braid segment within alarm distance of the skin spawns a
    # tracked proximity pair (= constraint solver rows) even while
    # inactive, so an alarm radius that swallows the rest gap makes
    # every substep pay for ~10^3 phantom contacts.
    # Scaled for braid_clearance = 0.15 mm (the soft-units operating
    # window: the bare bladder balloons unstably past ~500 Pa, by which
    # point radial swell is only ~0.1-0.2 mm, so the braid must engage
    # within that travel to act before the bladder's own cliff).
    # Alarm only 0.03 mm above contact: every braid-edge/skin-edge pair
    # inside the alarm radius becomes a tracked constraint row (LDL
    # back-solve each, every substep) even while inactive, and at
    # quasi-static sweep speeds (~µm/substep) 0.03 mm of warning is
    # still tens of substeps. Alarm at 0.12 mm made pre-engagement
    # levels ~10x slower for nothing.
    CONTACT_ALARM_DISTANCE = 8.0e-5    # m — proximity tracking radius
    CONTACT_DISTANCE       = 5.0e-5    # m — effective braid strand radius
    # Per-model penalty stiffness. Pressure load reaching each braid
    # node is ~mN-scale in the soft-units window, so k ~ 1e3 N/m keeps
    # penetration at a few µm without injecting chatter.
    CONTACT_STIFFNESS      = 2.0e3     # N/m per contact

