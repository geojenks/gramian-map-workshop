"""
parametricGripper.py — main SOFA scene for the actuator-characterization
workflow.

Binary toggle between two CAD inputs:
  - USE_CUSTOM_CAD = True  → cads/<family>/<instance>/ (your custom mesh, SI units)
  - USE_CUSTOM_CAD = False → cads/tutorial/ (bundled tutorial pneunet, mm units)

Both branches use the same FEM / topology / controller; only the meshes
and unit-dependent constants change. CAD selection = the CAD_NAME env var
(path relative to cads/, e.g. mckibben/v2_30deg).

Run from this folder (or anywhere; paths resolve relative
to this script):
    runSofa parametricGripper.py

First-time setup for a custom CAD (each CAD lives in cads/<family>/<instance>/):
    python convert_msh_to_v2.py cads/pneunet/source/pneunet.msh cads/pneunet/source/mesh.msh
    python preprocess.py cads/pneunet/source/mesh.msh cads/pneunet/source/actuator.npz

See docs/ACTUATOR_FROM_A_MESH.md in this repository for the whole route.
"""

