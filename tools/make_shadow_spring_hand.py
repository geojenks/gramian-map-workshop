"""Write a copy of the menagerie Shadow hand with a joint spring on the
four fingers' distal joints (J1), or on the coupled J1/J2 pair.

    python tools/make_shadow_spring_hand.py --k 0.002 [--joints J1|J1J2]
                                            [--springref 0.0] [--menagerie DIR]

Writes data/hands/shadow_spring/<variant>/hand.xml, a copy of
shadow_hand/right_hand.xml in which the joints rh_FFJ1, rh_MFJ1, rh_RFJ1,
rh_LFJ1 (and, with --joints J1J2, rh_*J2 too) carry stiffness="<k>"
(N.m/rad) and springref="<springref>" (rad), and whose meshdir points at the
menagerie's shadow_hand/assets relative to the new file. The thumb is left
alone (it has as many inputs as joints). Nothing else changes, so the hold
leader and placement made for "shadow" apply to every copy.

The copy's meshdir is relative to where the menagerie sits on this machine,
so the copies are regenerated by whatever runs them (tools/
hold_shadow_model_spring.py) and are not committed. The variant name is
j1_k<k> or j1j2_k<k>, with _ref<springref> appended when it is not 0.

Why J1: the reading we are testing is that the real hand's J2 flexes first
and J1 follows when J2 reaches its stop, so a spring (or the stop's
reaction) sits on J1. The pose solved by follow.py is unchanged by the
spring: follow.py reads a model spring as a torque load k (q - springref)
at the pose (follow._spring_item), not as a reaction to deflection.
"""
import argparse
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

FINGERS = ("FF", "MF", "RF", "LF")


def variant_name(k, joints, springref, ref_label=None):
    s = f"{joints.lower()}_k{k:g}"
    if ref_label:
        s += f"_ref{ref_label}"
    elif springref:
        s += f"_ref{springref:g}"
    return s


def make(k, joints="J1", springref=0.0, menagerie=None, out_root=None, ref_label=None):
    """Write the copy and return (variant name, path to its hand.xml).
    springref: one angle for every sprung joint, or {joint name: angle}
    (then ref_label names the variant, e.g. "posed")."""
    from gramian_workshop.hands import DEFAULT_MENAGERIE
    men = menagerie or os.environ.get("GMW_MENAGERIE", DEFAULT_MENAGERIE)
    src = os.path.join(men, "shadow_hand", "right_hand.xml")
    with open(src, encoding="utf-8") as fh:
        xml = fh.read()
    refs = springref if isinstance(springref, dict) else None
    name = variant_name(k, joints, 0.0 if refs else springref, ref_label)
    out_dir = os.path.join(out_root or os.path.join(ROOT, "data", "hands", "shadow_spring"), name)
    os.makedirs(out_dir, exist_ok=True)
    assets = os.path.relpath(os.path.join(men, "shadow_hand", "assets"), out_dir).replace("\\", "/")
    n_mesh = xml.count('meshdir="assets"')
    assert n_mesh == 1, n_mesh
    xml = xml.replace('meshdir="assets"', f'meshdir="{assets}"')
    jnums = {"J1": ("1",), "J1J2": ("1", "2")}[joints]
    n = 0
    for f in FINGERS:
        for j in jnums:
            pat = f'<joint name="rh_{f}J{j}" class="middle_distal"/>'
            assert xml.count(pat) == 1, pat
            ref = refs[f"rh_{f}J{j}"] if refs else springref
            xml = xml.replace(pat, f'<joint name="rh_{f}J{j}" class="middle_distal" '
                                   f'stiffness="{k:g}" springref="{ref:.6g}"/>')
            n += 1
    reftxt = ("per joint " + ", ".join(f"{a} {b:.4f}" for a, b in sorted(refs.items()))
              if refs else f"{springref:g}")
    head = (f"<!-- written by tools/make_shadow_spring_hand.py from {src}: "
            f"stiffness {k:g} N.m/rad, springref {reftxt} rad on {n} joints ({joints}); "
            f"meshdir is relative to this machine's menagerie, regenerate rather than copy -->\n")
    path = os.path.join(out_dir, "hand.xml")
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(head + xml)
    return name, path


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--k", type=float, required=True, help="N.m/rad")
    ap.add_argument("--joints", choices=("J1", "J1J2"), default="J1")
    ap.add_argument("--springref", type=float, default=0.0, help="rad")
    ap.add_argument("--menagerie", default=None)
    a = ap.parse_args()
    name, path = make(a.k, a.joints, a.springref, a.menagerie)
    print(name, os.path.relpath(path, ROOT))


if __name__ == "__main__":
    main()
